// End-to-end against a separate testing database. Prepare with prepare-bale-browser-test.php.
const puppeteer = require('puppeteer');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');

async function main() {
    const origin = 'http://127.0.0.1:8127';
    const output = 'artifacts/bale-workflow';
    const account = JSON.parse(await fs.readFile('storage/framework/bale-browser-session.json', 'utf8'));
    await fs.mkdir(output, { recursive: true });
    const browser = await puppeteer.launch({ headless: true });
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
    const clickText = async (selector, text) => {
        await page.waitForFunction((selector, text) => [...document.querySelectorAll(selector)].some(node => node.textContent.trim() === text), {}, selector, text);
        return page.$$eval(selector, (nodes, text) => {
        const node = nodes.find(node => node.textContent.trim() === text);
        if (!node) throw new Error(`Missing control: ${text}`);
        node.click();
        }, text);
    };
    const field = async (label, value) => page.evaluate((label, value) => {
        const container = [...document.querySelectorAll('label')].find(node => node.querySelector(':scope > span')?.textContent.trim() === label);
        const input = container?.querySelector('input, select');
        if (!input) throw new Error(`Missing field: ${label}`);
        const prototype = input.tagName === 'SELECT' ? HTMLSelectElement.prototype : HTMLInputElement.prototype;
        Object.getOwnPropertyDescriptor(prototype, 'value').set.call(input, value);
        input.dispatchEvent(new Event(input.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
    }, label, String(value));
    const goto = async path => page.goto(origin + path, { waitUntil: 'networkidle0' });
    try {
        await page.setViewport({ width: 1440, height: 1050 });
        await goto('/admin/login');
        await page.type('input[name="email"]', account.email);
        await page.type('input[name="password"]', account.password);
        await page.click('button[type="submit"]');
        await page.waitForFunction(() => location.pathname === '/admin/dashboard');
        await goto('/admin/suppliers');
        await clickText('button', '+ Add supplier');
        await page.waitForSelector('[role="dialog"] input');
        await page.screenshot({ path: `${output}/supplier-modal.png`, fullPage: true });
        await page.keyboard.press('Escape');
        await page.waitForSelector('[role="dialog"]', { hidden: true });
        await clickText('button', '+ Add supplier');
        await page.waitForSelector('[role="dialog"] input');
        await field('Name', account.supplier_name);
        await field('Phone (optional)', '09123456789');
        await clickText('button', 'Add supplier');
        await page.waitForFunction(name => [...document.querySelectorAll('tbody td')].some(node => node.textContent.includes(name)), {}, account.supplier_name);
        await goto('/admin/bales?new=1');
        await page.waitForSelector('[role="dialog"] input[role="combobox"]');
        await page.type('[role="dialog"] input[role="combobox"]', 'not-a-real-supplier');
        await page.waitForFunction(() => document.body.innerText.includes('No matching suppliers'));
        await page.focus('[role="dialog"] input[role="combobox"]');
        await page.keyboard.down('Control');
        await page.keyboard.press('a');
        await page.keyboard.up('Control');
        await page.keyboard.press('Backspace');
        await page.type('[role="dialog"] input[role="combobox"]', '09123456789');
        await page.waitForSelector('[role="option"]');
        assert.equal(await page.$$eval('[role="option"]', nodes => nodes.every(node => node.textContent.includes('09123456789'))), true);
        await page.focus('[role="dialog"] input[role="combobox"]');
        await page.keyboard.down('Control');
        await page.keyboard.press('a');
        await page.keyboard.up('Control');
        await page.keyboard.press('Backspace');
        await page.type('[role="dialog"] input[role="combobox"]', account.supplier_name);
        await page.waitForSelector('[role="option"]');
        await page.keyboard.press('ArrowDown');
        await page.keyboard.press('Enter');
        const controls = await page.$$eval('.bale-purchase-field > input, .bale-purchase-field > select, .bale-supplier-control', nodes => nodes.map(node => ({ height: node.getBoundingClientRect().height, top: node.getBoundingClientRect().top })));
        assert.equal(controls.every(control => control.height === 40), true, 'Purchase controls must share the same height');
        assert.equal(controls[0].top, controls[1].top, 'Supplier and branch controls must align');
        await page.screenshot({ path: `${output}/buy-bale-modal.png`, fullPage: true });
        await page.setViewport({ width: 390, height: 844 });
        await page.screenshot({ path: `${output}/buy-bale-modal-mobile.png`, fullPage: true });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.setViewport({ width: 1440, height: 1050 });
        await field('Branch', account.location_id);
        await field('Purchase cost', 12000);
        await field('Garment count (optional)', 4);
        await clickText('button', 'Record purchase');
        await page.waitForFunction(() => /^\/admin\/bales\/\d+$/.test(location.pathname));
        const balePath = new URL(page.url()).pathname;
        await clickText('button', 'Start laundry');
        await page.waitForFunction(() => document.body.innerText.includes('Laundry finished'));
        await field('Laundry cost (enter 0 if none)', 2000);
        await clickText('button', 'Ready for sale');
        await page.waitForFunction(() => [...document.querySelectorAll('button')].some(node => node.textContent === 'Create barcode'));
        await field('Selling price', 5000);
        await clickText('button', 'Create barcode');
        await page.waitForFunction(() => document.querySelectorAll('tbody code').length === 1);
        await field('Selling price', 7000);
        await clickText('button', 'Create barcode');
        await page.waitForFunction(() => document.querySelectorAll('tbody code').length === 2);
        const codes = await page.$$eval('tbody code', nodes => nodes.map(node => node.textContent));
        await goto(`${balePath}/labels`);
        await page.waitForSelector('.bale-print-label');
        await page.screenshot({ path: `${output}/price-labels.png`, fullPage: true });
        await page.bringToFront();
        await page.pdf({ path: `${output}/price-labels.pdf`, preferCSSPageSize: true, printBackground: true, waitForFonts: false, timeout: 15000 });
        assert.equal(await page.$$eval('.bale-print-label svg rect', nodes => nodes.length > 20), true);
        await goto('/admin/pos');
        await page.waitForSelector('select[aria-label="POS branch"]');
        await page.select('select[aria-label="POS branch"]', String(account.location_id));
        await page.waitForFunction(() => !document.querySelector('input[aria-label="Scan barcode"]').disabled);
        const scan = async code => {
            await page.type('input[aria-label="Scan barcode"]', code);
            await page.keyboard.press('Enter');
            await page.waitForFunction(() => document.querySelector('input[aria-label="Scan barcode"]').value === '' && !document.querySelector('input[aria-label="Scan barcode"]').disabled);
        };
        await scan(codes[0]); await scan(codes[0]); await scan(codes[1]);
        assert.ok(await page.$eval('.bale-pos-total', node => node.textContent.includes('17,000')));
        await page.type('input[aria-label="Cash received"]', '20000');
        await page.screenshot({ path: `${output}/pos-ready.png`, fullPage: true });
        await clickText('button', 'Complete sale');
        await page.waitForSelector('.bale-sale-success');
        assert.ok(await page.$eval('.bale-sale-success', node => node.textContent.includes('3,000')));
        const receiptUrl = await page.$eval('.bale-sale-success a', node => node.href);
        const receipt = await browser.newPage();
        await receipt.goto(receiptUrl, { waitUntil: 'networkidle0' });
        await receipt.screenshot({ path: `${output}/receipt.png`, fullPage: true });
        await receipt.close();
        await goto(balePath);
        await page.waitForSelector('.bale-stats');
        assert.ok(await page.$eval('.bale-stats', node => node.textContent.includes('17,000')));
        await page.screenshot({ path: `${output}/bale-after-sale.png`, fullPage: true });
        await clickText('.bale-return-form summary', 'Return garments');
        await clickText('.bale-return-form button', 'Record return & paid refund');
        await page.waitForFunction(() => document.body.innerText.includes('Garments returned and refund payment recorded.'));
        await goto(`/admin/finance?location_id=${account.location_id}`);
        await page.waitForSelector('.bale-stats');
        const financeText = await page.$eval('.bale-stats', node => node.textContent);
        assert.ok(financeText.includes('17,000') && financeText.includes('19,000') && financeText.includes('-2,000'), financeText);
        await page.screenshot({ path: `${output}/finance.png`, fullPage: true });
        await goto(balePath);
        await page.setViewport({ width: 390, height: 844 });
        await page.screenshot({ path: `${output}/bale-mobile.png`, fullPage: true });
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile bale page must not overflow');
        assert.deepEqual(errors, [], 'No JavaScript errors');
        console.log('PASS: real login, supplier, bale purchase, laundry, fixed price groups, barcode labels/PDF, repeated scans, direct checkout, receipt, garment refund, finance, and mobile layout.');
    } catch (error) {
        await page.screenshot({ path: `${output}/failure.png`, fullPage: true });
        console.error('Browser state:', await page.evaluate(() => ({ path: location.pathname, alerts: [...document.querySelectorAll('[role="alert"], .flash')].map(node => node.textContent).slice(0, 5) })));
        throw error;
    } finally { await browser.close(); }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
